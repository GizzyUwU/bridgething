				if let content = try? container.decode(Data.self, forKey: .data) {
					self = .bytes(content)
					return
				}
			}
		}
		throw DecodingError.typeMismatch(Image.self, DecodingError.Context(codingPath: decoder.codingPath, debugDescription: "Wrong type for Image"))
	}

	public func encode(to encoder: Encoder) throws {
		var container = encoder.container(keyedBy: ContainerCodingKeys.self)
		switch self {
		case .id(let content):
			try container.encode(CodingKeys.id, forKey: .type)
			try container.encode(content, forKey: .data)
		case .bytes(let content):
			try container.encode(CodingKeys.bytes, forKey: .type)
			try container.encode(content, forKey: .data)
		}
	}
}

