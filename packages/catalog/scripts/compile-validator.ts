#!/usr/bin/env bun
import addFormats from 'ajv-formats';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import schema from '../schema.v1.json' with { type: 'json' };

const here = new URL('.', import.meta.url).pathname;

export const VALIDATOR_PATH = resolve(here, '..', 'src', 'generated', 'schema.v1.validator.mjs');
export const VALIDATOR_TYPES_PATH = resolve(here, '..', 'src', 'generated', 'schema.v1.validator.d.mts');

const BANNER = '// generated by packages/catalog/scripts/compile-validator.ts from schema.v1.json; do not edit.\n';

export async function buildValidatorSources(): Promise<{ code: string; types: string }> {
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
  addFormats(ajv);

  const scratch = resolve(here, '.compile-validator');
  await rm(scratch, { recursive: true, force: true });
  await mkdir(scratch, { recursive: true });

  try {
    const entry = join(scratch, 'validator.cjs');
    await writeFile(entry, standaloneCode(ajv, ajv.compile(schema)));

    const built = await Bun.build({ entrypoints: [entry], format: 'esm', target: 'browser', minify: false });
    if (!built.success) {
      for (const log of built.logs) console.error(log);
      throw new Error('bundling the standalone validator failed');
    }

    return {
      code: BANNER + (await built.outputs[0]!.text()),
      types: [
        BANNER.trimEnd(),
        '',
        'export type SchemaError = { instancePath: string; message?: string };',
        '',
        'declare const validate: ((data: unknown) => boolean) & { errors?: SchemaError[] | null };',
        'export default validate;',
        '',
      ].join('\n'),
    };
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const { code, types } = await buildValidatorSources();
  await writeFile(VALIDATOR_PATH, code);
  await writeFile(VALIDATOR_TYPES_PATH, types);
  console.log(`wrote ${VALIDATOR_PATH}`);
}
