fn push_gateway_surface_class(out: &mut String, s: &Surface) {
  out.push_str(&format!(
    "/** Cross-peer methods for the `{}` wire surface. */\npublic class {}Surface(private val gateway: BridgethingGateway) {{\n",
    s.name, s.name
  ));
  push_inbound_flows_gateway(out, s);
  push_outbound_methods_gateway(out, s);
  push_query_methods_gateway(out, s);
  push_request_flows(out, s, /* device_scope */ false);
  out.push_str("}\n\n");
}

fn push_inbound_flows_gateway(out: &mut String, s: &Surface) {
  let Some(e) = &s.inbound else {
    return;
  };
  let outer = &e.outer_variant;
  let leaf = e.inner_variants.is_empty();
  if leaf && e.outer_payload.is_some() {
    let payload_kt = e.outer_payload.as_ref().map(|p| p.kotlin()).unwrap();
    out.push_str(&format!(
      "  /** Stream of `{}` messages, paired with the originating device id. */\n  public val all: Flow<Pair<String, {payload_kt}>> = gateway.events\n    .filterIsInstance<GatewayEvent.Message>()\n    .mapNotNull {{\n      val data = it.message.data as? BridgeToGatewayMsgData.{outer} ?: return@mapNotNull null\n      it.deviceId to data.data\n    }}\n\n",
      s.name
    ));
    return;
  }
  if leaf {
    return;
  }
  let outer_payload_type = match e.outer_payload.as_ref() {
    Some(PayloadType::Named(n)) => n.clone(),
    _ => String::new(),
  };
  for iv in s.inbound_event_variants() {
    let prop = rename_camel(&iv.variant);
    let pair_type = match &iv.payload {
      Some(p) => format!("Pair<String, {}>", p.kotlin()),
      None => "String".to_string(),
    };
    let yield_body = match &iv.payload {
      Some(_) => format!(
        "      val outer = it.message.data as? BridgeToGatewayMsgData.{outer} ?: return@mapNotNull null\n      val inner = outer.data as? {outer_payload_type}.{} ?: return@mapNotNull null\n      it.deviceId to inner.data\n",
        iv.variant
      ),
      None => format!(
        "      val outer = it.message.data as? BridgeToGatewayMsgData.{outer} ?: return@mapNotNull null\n      if (outer.data !is {outer_payload_type}.{}) return@mapNotNull null\n      it.deviceId\n",
        iv.variant
      ),
    };
    out.push_str(&format!(
      "  /** Cross-peer stream of `{}::{}` messages. */\n  public val {prop}: Flow<{pair_type}> = gateway.events\n    .filterIsInstance<GatewayEvent.Message>()\n    .mapNotNull {{\n{yield_body}    }}\n\n",
      s.name, iv.variant
    ));
  }
}

fn push_outbound_methods_gateway(out: &mut String, s: &Surface) {
  let Some(e) = &s.outbound else {
    return;
  };
  let category_meta = match e.category {
    EntryCategory::Event => "GatewayMsgMeta.Event",
    EntryCategory::Command => "GatewayMsgMeta.Command",
    EntryCategory::Skip => "GatewayMsgMeta.Event",
  };
  let leaf = e.inner_variants.is_empty();
  if leaf && e.outer_payload.is_some() {
    let payload_kt = e.outer_payload.as_ref().map(|p| p.kotlin()).unwrap();
    let device_param = if e.unicast { "deviceId: String, " } else { "" };
    let body = if e.unicast {
      format!(
        "    val msg = GatewayToBridgeMsg(\n      id = UUID.randomUUID().toBytes(),\n      meta = {category_meta},\n      data = GatewayToBridgeMsgData.{}(payload),\n    )\n    gateway.send(deviceId, msg, priority)",
        e.outer_variant
      )
    } else {
      format!(
        "    val ids = gateway.connectedDeviceIds()\n    coroutineScope {{\n      ids.map {{ deviceId ->\n        async {{\n          val msg = GatewayToBridgeMsg(\n            id = UUID.randomUUID().toBytes(),\n            meta = {category_meta},\n            data = GatewayToBridgeMsgData.{}(payload),\n          )\n          gateway.send(deviceId, msg, priority)\n        }}\n      }}.awaitAll()\n    }}",
        e.outer_variant
      )
    };
    let doc = if e.unicast {
      format!("Send a `{}` event to a specific peer.", s.name)
    } else {
      format!("Send a `{}` event to every connected peer (broadcast).", s.name)
    };
    out.push_str(&format!(
      "  /** {doc} */\n  public suspend fun send({device_param}payload: {payload_kt}, priority: Priority = Priority.Normal) {{\n{body}\n  }}\n\n"
    ));
    return;
  }
  if leaf {
    return;
  }
  let outer_payload_type = match e.outer_payload.as_ref() {
    Some(PayloadType::Named(n)) => n.clone(),
    _ => String::new(),
  };
  for iv in s.outbound_send_variants() {
    let method = rename_camel(&iv.variant);
    let device_param = if e.unicast { "deviceId: String, " } else { "" };
    let (param, inner_expr) = match &iv.payload {
      Some(p) => (
        format!("payload: {}, ", p.kotlin()),
        format!("{outer_payload_type}.{}(payload)", iv.variant),
      ),
      None => (String::new(), format!("{outer_payload_type}.{}", iv.variant)),
    };
    let data_expr = format!("GatewayToBridgeMsgData.{}({inner_expr})", e.outer_variant);
    let body = if e.unicast {
      format!(
        "    val msg = GatewayToBridgeMsg(\n      id = UUID.randomUUID().toBytes(),\n      meta = {category_meta},\n      data = {data_expr},\n    )\n    gateway.send(deviceId, msg, priority)"
      )
    } else {
      format!(
        "    val ids = gateway.connectedDeviceIds()\n    coroutineScope {{\n      ids.map {{ deviceId ->\n        async {{\n          val msg = GatewayToBridgeMsg(\n            id = UUID.randomUUID().toBytes(),\n            meta = {category_meta},\n            data = {data_expr},\n          )\n          gateway.send(deviceId, msg, priority)\n        }}\n      }}.awaitAll()\n    }}"
      )
    };
    let doc = if e.unicast {
      format!("Send `{}::{}` to a specific peer.", s.name, iv.variant)
    } else {
      format!("Send `{}::{}` to every connected peer (broadcast).", s.name, iv.variant)
    };
    out.push_str(&format!(
      "  /** {doc} */\n  public suspend fun {method}({device_param}{param}priority: Priority = Priority.Normal) {{\n{body}\n  }}\n\n"
    ));
  }
}

fn push_query_methods_gateway(out: &mut String, s: &Surface) {
  for r in &s.outbound_queries {
    push_query_method_gateway(out, r);
  }
}

fn push_query_method_gateway(out: &mut String, r: &TypedRequestEntry) {
  let method = rename_camel(&r.request_variant_pascal());
  let req_param = if r.request_takes_payload {
    format!(", req: {}", r.request)
  } else {
    String::new()
  };
  let domain = r.error.as_deref().unwrap_or("Nothing");
  let request_pascal = r.request_variant_pascal();
  let response_pascal = r.response_variant_pascal();
  let outbound_inner = if r.request_takes_payload {
    format!("GatewayToBridge{}Msg.{}(req)", r.surface, request_pascal)
  } else {
    format!("GatewayToBridge{}Msg.{}", r.surface, request_pascal)
  };
  out.push_str(&format!(
    "  /** Typed request to a specific peer: companion sends, daemon responds. */\n  public suspend fun {method}(deviceId: String{req_param}, timeout: Duration = 30.seconds): RequestResult<{}, {domain}> {{\n",
    r.response
  ));
  out.push_str(&format!(
    "    val outboundData = GatewayToBridgeMsgData.{}({outbound_inner})\n",
    r.surface
  ));
  out.push_str("    val response = gateway.request(deviceId, outboundData, timeout)\n");
  out.push_str("    return when (val d = response.data) {\n");
  out.push_str(&format!(
    "      is BridgeToGatewayMsgData.{} -> when (val inner = d.data) {{\n",
    r.surface
  ));
  out.push_str(&format!(
    "        is BridgeToGateway{}Msg.{} -> RequestResult.Ok(inner.data)\n",
    r.surface, response_pascal
  ));
  if let Some(err_pascal) = r.error_variant_pascal() {
    out.push_str(&format!(
      "        is BridgeToGateway{}Msg.{err_pascal} -> RequestResult.DomainErr(inner.data)\n",
      r.surface
    ));
  }
  out.push_str("        else -> RequestResult.ProtocolErr(GatewayError.Unsupported)\n");
  out.push_str("      }\n");
  out.push_str("      is BridgeToGatewayMsgData.Error -> RequestResult.ProtocolErr(d.data)\n");
  out.push_str("      else -> RequestResult.ProtocolErr(GatewayError.Unsupported)\n");
  out.push_str("    }\n  }\n\n");
}

fn push_request_flows(out: &mut String, s: &Surface, device_scope: bool) {
  for r in &s.inbound_requests {
    push_request_flow(out, r, device_scope);
  }
}

fn push_request_flow(out: &mut String, r: &TypedRequestEntry, device_scope: bool) {
  let request_pascal = r.request_variant_pascal();
  let pair_type = if r.request_takes_payload {
    format!("Pair<{}Handle, {}>", r.request, r.request)
  } else {
    format!("{}Handle", r.request)
  };

  let scope_filter = if device_scope {
    "    .filter { it.deviceId == deviceId }\n"
  } else {
    ""
  };
  let yield_pair = if r.request_takes_payload {
    "      handle to inner.data\n"
  } else {
    "      handle\n"
  };
  out.push_str(&format!(
    "  /** Stream of typed inbound `{}` requests. */\n  public val requests: Flow<{pair_type}> = gateway.events\n    .filterIsInstance<GatewayEvent.Message>()\n    .filter {{ it.message.meta is GatewayMsgMeta.Request }}\n{scope_filter}    .mapNotNull {{\n      val outer = it.message.data as? BridgeToGatewayMsgData.{} ?: return@mapNotNull null\n      val inner = outer.data as? BridgeToGateway{}Msg.{request_pascal} ?: return@mapNotNull null\n      val handle = {}Handle(gateway, it.deviceId, it.message.id)\n{yield_pair}    }}\n\n",
    r.request, r.surface, r.surface, r.request
  ));
}

