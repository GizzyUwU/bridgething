//! Kotlin emitter for surface-namespaced gateway dispatch.
//!
//! Each surface gets two classes:
//! - `<Name>Surface` — gateway-level: cross-peer Flows, broadcast sends,
//!   typed queries with explicit deviceId parameter.
//! - `<Name>SurfaceForDevice` — per-peer: filtered Flows with no deviceId
//!   in the pair, deviceId-baked sends, deviceId-baked typed queries.
//!
//! `BridgethingGateway.<surface>` extension property returns a fresh
//! gateway-level surface; `BridgethingGateway.device(deviceId)` returns a
//! `BridgethingGatewayDevice` proxy whose surfaces are device-scoped.

use std::{collections::BTreeSet, path::Path};

use anyhow::{Context, Result};

use super::{
  inventory::PayloadType,
  plan::{EntryCategory, Plan, Surface, TypedRequestEntry, rename_camel, surfaces},
};

const KOTLIN_OUTPUT: &str =
  "packages/gateway/kotlin/gateway/src/main/kotlin/dev/bridgething/gateway/Dispatch.generated.kt";
const KOTLIN_PACKAGE: &str = "dev.bridgething.gateway";
const KOTLIN_SCHEMA_PACKAGE: &str = "dev.bridgething.schema";

pub fn emit_kotlin(plan: &Plan) -> Result<()> {
  let surfaces = surfaces(plan);
  let mut out = String::new();
  out.push_str("// THIS FILE IS GENERATED BY tools/codegen. Do not edit by hand.\n");
  out.push_str("// Re-generate with `just codegen` (or `just kotlin`).\n\n");
  out.push_str(&format!("package {KOTLIN_PACKAGE}\n\n"));
  out.push_str(&format!("import {KOTLIN_SCHEMA_PACKAGE}.*\n"));
  out.push_str("import kotlinx.coroutines.async\n");
  out.push_str("import kotlinx.coroutines.awaitAll\n");
  out.push_str("import kotlinx.coroutines.coroutineScope\n");
  out.push_str("import kotlinx.coroutines.flow.Flow\n");
  out.push_str("import kotlinx.coroutines.flow.filter\n");
  out.push_str("import kotlinx.coroutines.flow.filterIsInstance\n");
  out.push_str("import kotlinx.coroutines.flow.mapNotNull\n");
  out.push_str("import java.util.UUID\n");
  out.push_str("import kotlin.time.Duration\n");
  out.push_str("import kotlin.time.Duration.Companion.seconds\n\n");

  if !plan.outbound_requests.is_empty() || !plan.inbound_requests.is_empty() {
    out.push_str(&kotlin_request_result_class());
  }

  for s in &surfaces {
    push_gateway_surface_class(&mut out, s);
  }

  for s in &surfaces {
    push_device_surface_class(&mut out, s);
  }

  push_device_proxy_class(&mut out, &surfaces);

  for s in &surfaces {
    out.push_str(&format!(
      "/** Methods scoped to the `{}` wire surface. */\npublic val BridgethingGateway.{}: {}Surface\n  get() = {}Surface(this)\n\n",
      s.name, s.prop, s.name, s.name
    ));
  }
  out.push_str("/** Returns a per-device proxy with `deviceId` baked into every method and Flow. */\npublic fun BridgethingGateway.device(deviceId: String): BridgethingGatewayDevice = BridgethingGatewayDevice(this, deviceId)\n\n");

  let bridge_request_types: BTreeSet<String> = plan.inbound_requests.iter().map(|r| r.request.clone()).collect();
  let _ = bridge_request_types;

  for s in &surfaces {
    for r in &s.inbound_requests {
      out.push_str(&kotlin_request_handle_class(r));
    }
  }

  std::fs::create_dir_all(Path::new(KOTLIN_OUTPUT).parent().unwrap()).context("ensure kotlin dispatch dir")?;
  std::fs::write(KOTLIN_OUTPUT, out).context("write kotlin dispatch")?;
  Ok(())
}

fn kotlin_request_result_class() -> String {
  r#"/** Outcome of a typed gateway request. */
public sealed class RequestResult<out R, out E> {
  public data class Ok<R>(val response: R): RequestResult<R, Nothing>()
  public data class DomainErr<E>(val error: E): RequestResult<Nothing, E>()
  public data class ProtocolErr(val error: GatewayError): RequestResult<Nothing, Nothing>()
}

"#
  .to_string()
}

