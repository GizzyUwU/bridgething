fn push_apply_dispatch(out: &mut String, surfaces: &[Surface]) {
  out.push_str("type GatewaySurfaceCache = {\n");
  for s in surfaces {
    out.push_str(&format!("  {}?: {}Surface;\n", s.prop, s.name));
  }
  out.push_str("};\n\n");

  out.push_str("/**\n * Apply codegen-emitted prototype augmentations to BridgethingGateway.\n * Called once from `index.ts` after the class definition. Idempotent.\n */\nexport function applyDispatch(): void {\n");
  out.push_str("  const surfaceCache = new WeakMap<BridgethingGateway, GatewaySurfaceCache>();\n");
  out.push_str("  function bucketFor(g: BridgethingGateway): GatewaySurfaceCache {\n    let bucket = surfaceCache.get(g);\n    if (!bucket) { bucket = {}; surfaceCache.set(g, bucket); }\n    return bucket;\n  }\n\n");
  for s in surfaces {
    out.push_str(&format!(
      "  Object.defineProperty(BridgethingGateway.prototype, '{}', {{\n    configurable: true,\n    enumerable: true,\n    get(this: BridgethingGateway): {}Surface {{\n      const bucket = bucketFor(this);\n      return (bucket.{} ??= new {}Surface(this));\n    }},\n  }});\n",
      s.prop, s.name, s.prop, s.name
    ));
  }
  out.push('\n');

  out.push_str("  const deviceCache = new WeakMap<BridgethingGateway, Map<string, BridgethingGatewayDevice>>();\n");
  out.push_str("  BridgethingGateway.prototype.device = function (deviceId: string): BridgethingGatewayDevice {\n    let cache = deviceCache.get(this);\n    if (!cache) { cache = new Map(); deviceCache.set(this, cache); }\n    let proxy = cache.get(deviceId);\n    if (!proxy) { proxy = new BridgethingGatewayDevice(this, deviceId); cache.set(deviceId, proxy); }\n    return proxy;\n  };\n\n");

  out.push_str("  BridgethingGateway.prototype.subscribe = function (handlers: BridgeMessageHandlers): () => void {\n    return outerSubscribeGateway(this, handlers, false);\n  };\n");
  out.push_str("  BridgethingGateway.prototype.subscribePartial = function (handlers: PartialBridgeMessageHandlers): () => void {\n    return outerSubscribeGateway(this, handlers, true);\n  };\n");
  out.push_str("}\n\n");

  push_outer_subscribe_gateway(out, surfaces);
  push_outer_subscribe_device(out, surfaces);
}

fn push_outer_subscribe_gateway(out: &mut String, surfaces: &[Surface]) {
  out.push_str("function outerSubscribeGateway(g: BridgethingGateway, handlers: PartialBridgeMessageHandlers, partial: boolean): () => void {\n  return g.on((event: GatewayEvent) => {\n    if (event.type !== 'message') return;\n    const data = event.message.data;\n    switch (data.type) {\n");
  for s in surfaces {
    push_outer_case_gateway(out, s);
  }
  out.push_str("      default: {\n        if (!partial) g.logger.warn('subscribe: no handler for unknown wire variant', data);\n        return;\n      }\n    }\n  });\n}\n\n");
}

fn push_outer_case_gateway(out: &mut String, s: &Surface) {
  if outer_gateway_value(s).is_none() {
    return;
  }
  let prop = &s.prop;
  let leaf_only = s
    .inbound
    .as_ref()
    .map(|e| e.inner_variants.is_empty() && e.outer_payload.is_some())
    .unwrap_or(false);
  let has_typed_req = !s.inbound_requests.is_empty();
  let single_request_only = s.inbound_event_variants().is_empty() && s.inbound_requests.len() == 1;
  if leaf_only && !has_typed_req {
    out.push_str(&format!(
      "      case '{prop}': {{\n        const handler = handlers.{prop};\n        if (!handler) {{ if (!partial) g.logger.warn('subscribe: no handler for {prop}'); return; }}\n        handler(event.deviceId, data.data);\n        return;\n      }}\n"
    ));
    return;
  }
  if single_request_only {
    let r = &s.inbound_requests[0];
    let payload_pass = if r.request_takes_payload {
      ", data.data.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "      case '{prop}': {{\n        if (event.message.meta.kind !== 'request') return;\n        const handler = handlers.{prop};\n        if (!handler) {{ if (!partial) g.logger.warn('subscribe: no handler for {prop}'); return; }}\n        const handle = new {}Handle(g, event.deviceId, event.message.id);\n        const result = handler(handle{payload_pass});\n        if (result && typeof result.then === 'function') result.catch((err: unknown) => g.logger.error('subscribe handler threw:', err));\n        return;\n      }}\n",
      r.request
    ));
    return;
  }
  let inner_tag = s
    .inbound
    .as_ref()
    .and_then(|e| e.inner_tag_field.as_deref())
    .unwrap_or("event");
  out.push_str(&format!(
    "      case '{prop}': {{\n        const innerHandlers = handlers.{prop};\n        if (!innerHandlers) {{ if (!partial) g.logger.warn('subscribe: no handler for {prop}'); return; }}\n        const inner = data.data;\n        switch (inner.{inner_tag}) {{\n"
  ));
  for iv in s.inbound_event_variants() {
    let invoke = match &iv.payload {
      Some(_) => format!("            innerHandlers.{}?.(event.deviceId, inner.data);", iv.disc),
      None => format!("            innerHandlers.{}?.(event.deviceId);", iv.disc),
    };
    out.push_str(&format!(
      "          case '{}': {{\n{invoke}\n            return;\n          }}\n",
      iv.disc
    ));
  }
  for r in &s.inbound_requests {
    let pass_payload = if r.request_takes_payload {
      ", inner.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "          case '{}': {{\n            if (event.message.meta.kind !== 'request') return;\n            const handler = innerHandlers.{};\n            if (!handler) {{ if (!partial) g.logger.warn('{}: no handler for inner', '{}'); return; }}\n            const handle = new {}Handle(g, event.deviceId, event.message.id);\n            const result = handler(handle{pass_payload});\n            if (result && typeof result.then === 'function') result.catch((err: unknown) => g.logger.error('subscribe handler threw:', err));\n            return;\n          }}\n",
      r.request_disc, r.request_disc, s.name, r.request_disc, r.request
    ));
  }
  out.push_str(&format!(
    "          default: {{\n            if (!partial) g.logger.warn('{}: no handler for inner', inner);\n            return;\n          }}\n        }}\n      }}\n",
    s.name
  ));
}

