//! TypeScript emitter for surface-namespaced gateway dispatch.
//!
//! Output shape:
//! - one `<Name>Surface` class per surface, accessed via
//!   `gateway.<name>` - broadcast methods and cross-peer listeners.
//! - one `<Name>SurfaceForDevice` class per surface, accessed via
//!   `gateway.device(id).<name>` - unicast methods and per-peer listeners.
//! - `BridgethingGatewayDevice` proxy class returned by `gateway.device(id)`.
//! - typed-switch dispatch in the runtime - no string-keyed lookups,
//!   no `as` casts in either generated dispatch or user code.

use std::{collections::BTreeSet, path::Path};

use anyhow::{Context, Result};

use super::{
  inventory::PayloadType,
  plan::{Plan, Surface, TypedRequestEntry, surfaces},
};

const TS_OUTPUT: &str = "packages/gateway/typescript/src/dispatch.generated.ts";

pub fn emit_typescript(plan: &Plan) -> Result<()> {
  let surfaces = surfaces(plan);
  let mut out = String::new();
  push_header(&mut out);
  push_imports(&mut out, &surfaces);
  push_typed_request_result(&mut out);

  for s in &surfaces {
    push_inbound_handlers_types(&mut out, s);
  }

  for s in &surfaces {
    push_gateway_surface_class(&mut out, s);
  }

  for s in &surfaces {
    push_device_surface_class(&mut out, s);
  }

  push_outer_handlers_types(&mut out, &surfaces);

  push_module_augmentation(&mut out, &surfaces);

  for s in &surfaces {
    for r in &s.inbound_requests {
      push_request_handle_class(&mut out, r);
    }
  }

  push_device_proxy_class(&mut out, &surfaces);

  push_apply_dispatch(&mut out, &surfaces);

  std::fs::create_dir_all(Path::new(TS_OUTPUT).parent().unwrap()).context("ensure ts dispatch dir")?;
  std::fs::write(TS_OUTPUT, out).context("write ts dispatch")?;
  Ok(())
}

fn push_header(out: &mut String) {
  out.push_str("// THIS FILE IS GENERATED BY tools/codegen. Do not edit by hand.\n");
  out.push_str("// Re-generate with `just codegen` (or `just typescript`).\n\n");
}

fn push_imports(out: &mut String, surfaces: &[Surface]) {
  let mut imports: BTreeSet<String> = BTreeSet::new();
  for s in surfaces {
    if let Some(e) = &s.inbound {
      if let Some(PayloadType::Named(n)) = &e.outer_payload {
        imports.insert(n.clone());
      }
      for iv in &e.inner_variants {
        if let Some(PayloadType::Named(n)) = &iv.payload {
          imports.insert(n.clone());
        }
      }
    }
    if let Some(e) = &s.outbound {
      if let Some(PayloadType::Named(n)) = &e.outer_payload {
        imports.insert(n.clone());
      }
      for iv in &e.inner_variants {
        if let Some(PayloadType::Named(n)) = &iv.payload {
          imports.insert(n.clone());
        }
      }
    }
    for r in s.outbound_queries.iter().chain(&s.inbound_requests) {
      if r.request_takes_payload {
        imports.insert(r.request.clone());
      }
      imports.insert(r.response.clone());
      if let Some(e) = &r.error {
        imports.insert(e.clone());
      }
    }
  }
  imports.insert("BridgeToGatewayMsg".to_string());
  imports.insert("WireError".to_string());
  imports.insert("GatewayToBridgeMsg".to_string());
  imports.insert("Priority".to_string());

  out.push_str("import {\n");
  for name in &imports {
    out.push_str(&format!("  type {name},\n"));
  }
  out.push_str("  newUuid,\n");
  out.push_str("} from '@bridgething/lib';\n");
  out.push_str("import { BridgethingGateway, type GatewayEvent } from './index';\n\n");
}

fn push_typed_request_result(out: &mut String) {
  out.push_str(
    "export type TypedRequestResult<R, E> =\n  | { ok: true; response: R }\n  | { ok: false; kind: 'domain'; error: E }\n  | { ok: false; kind: 'protocol'; error: WireError };\n\n",
  );
}

/// Two records per surface: one for gateway-level (deviceId in callback),
/// one for device-level (no deviceId). Only emitted when a surface has
/// >= 2 inbound entries.
fn push_inbound_handlers_types(out: &mut String, s: &Surface) {
  let entries = inbound_handler_entries(s);
  if entries.len() < 2 {
    return;
  }
  out.push_str(&format!("export type {}InboundHandlers = {{\n", s.name));
  for (k, gw_sig, _) in &entries {
    out.push_str(&format!("  {k}: {gw_sig};\n"));
  }
  out.push_str("};\n\n");

  out.push_str(&format!("export type {}DeviceInboundHandlers = {{\n", s.name));
  for (k, _, dev_sig) in &entries {
    out.push_str(&format!("  {k}: {dev_sig};\n"));
  }
  out.push_str("};\n\n");
}

/// Returns (key, gateway-level signature, device-level signature) for
/// each inbound entry of a surface (event variants + typed-request handles).
fn inbound_handler_entries(s: &Surface) -> Vec<(String, String, String)> {
  let mut keys: Vec<(String, String, String)> = Vec::new();
  for iv in s.inbound_event_variants() {
    let gw = match &iv.payload {
      Some(p) => format!("(deviceId: string, msg: {}) => void", p.ts()),
      None => "(deviceId: string) => void".to_string(),
    };
    let dev = match &iv.payload {
      Some(p) => format!("(msg: {}) => void", p.ts()),
      None => "() => void".to_string(),
    };
    keys.push((iv.disc.clone(), gw, dev));
  }
  for r in &s.inbound_requests {
    let payload_arg = if r.request_takes_payload {
      format!(", req: {}", r.request)
    } else {
      String::new()
    };
    let sig = format!("(handle: {}Handle{payload_arg}) => Promise<void> | void", r.request);
    keys.push((r.request_disc.clone(), sig.clone(), sig));
  }
  keys
}

