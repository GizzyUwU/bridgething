fn push_gateway_surface_class(out: &mut String, s: &Surface) {
  out.push_str(&format!("export class {}Surface {{\n", s.name));
  out.push_str("  constructor(private readonly _gateway: BridgethingGateway) {}\n\n");

  push_inbound_methods_gateway(out, s);
  push_subscribe_methods_gateway(out, s);
  push_outbound_methods_gateway(out, s);
  push_query_methods_gateway(out, s);

  out.push_str("}\n\n");
}

fn push_inbound_methods_gateway(out: &mut String, s: &Surface) {
  let Some(e) = &s.inbound else {
    // No inbound dispatch entry, but we may still have typed inbound
    // requests (e.g. Asset surface where BridgeToGatewayAssetMsg holds
    // only request/response variants - no event markers). Emit those.
    for r in &s.inbound_requests {
      push_request_handler_method_gateway(out, r);
    }
    return;
  };
  let leaf_inbound = e.inner_variants.is_empty();
  if leaf_inbound && e.outer_payload.is_some() {
    let payload_ts = e.outer_payload.as_ref().map(|p| p.ts()).unwrap();
    out.push_str(&format!(
      "  /** Subscribe to `{}` messages across all peers. */\n  on(handler: (deviceId: string, msg: {payload_ts}) => void): () => void {{\n    return this._gateway.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      handler(event.deviceId, data.data);\n    }});\n  }}\n\n",
      s.name, e.outer_disc
    ));
    return;
  }
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  for iv in s.inbound_event_variants() {
    let method = format!("on{}", iv.variant);
    let sig = match &iv.payload {
      Some(p) => format!("(deviceId: string, msg: {}) => void", p.ts()),
      None => "(deviceId: string) => void".to_string(),
    };
    let invoke = match &iv.payload {
      Some(_) => "handler(event.deviceId, inner.data);",
      None => "handler(event.deviceId);",
    };
    out.push_str(&format!(
      "  /** Subscribe to `{}::{}` across all peers. */\n  {method}(handler: {sig}): () => void {{\n    return this._gateway.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      if (inner.{inner_tag} !== '{}') return;\n      {invoke}\n    }});\n  }}\n\n",
      s.name, iv.variant, e.outer_disc, iv.disc
    ));
  }
  for r in &s.inbound_requests {
    push_request_handler_method_gateway(out, r);
  }
}

fn push_request_handler_method_gateway(out: &mut String, r: &TypedRequestEntry) {
  let payload_arg = if r.request_takes_payload {
    format!(", req: {}", r.request)
  } else {
    String::new()
  };
  let pass_payload = if r.request_takes_payload {
    ", inner.data".to_string()
  } else {
    String::new()
  };
  let method = format!("on{}", r.request_variant_pascal());
  out.push_str(&format!(
    "  /** Typed inbound `{}` request: handler is given a typed handle for the response. */\n  {method}(handler: (handle: {}Handle{payload_arg}) => Promise<void> | void): () => void {{\n    return this._gateway.on(event => {{\n      if (event.type !== 'message') return;\n      const message = event.message;\n      if (message.meta.kind !== 'request') return;\n      const data = message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      if (inner.{} !== '{}') return;\n      const handle = new {}Handle(this._gateway, event.deviceId, message.id);\n      const result = handler(handle{pass_payload});\n      if (result && typeof result.then === 'function') {{\n        result.catch((err: unknown) => {{ this._gateway.logger.error('on{} handler threw:', err); }});\n      }}\n    }});\n  }}\n\n",
    r.request, r.request, r.surface_disc, r.inner_tag, r.request_disc, r.request, r.request_variant_pascal()
  ));
}

fn push_subscribe_methods_gateway(out: &mut String, s: &Surface) {
  let total_inbound = s.inbound_event_variants().len() + s.inbound_requests.len();
  if total_inbound < 2 {
    return;
  }
  out.push_str(&format!(
    "  /** Exhaustive subscribe over all inbound `{}` variants. */\n  subscribe(handlers: {}InboundHandlers): () => void {{\n    return this._subscribe(handlers, false);\n  }}\n\n",
    s.name, s.name
  ));
  out.push_str(&format!(
    "  /** Same as `subscribe` but every handler is optional. */\n  subscribePartial(handlers: Partial<{}InboundHandlers>): () => void {{\n    return this._subscribe(handlers, true);\n  }}\n\n",
    s.name
  ));
  push_subscribe_impl_gateway(out, s);
}

fn push_subscribe_impl_gateway(out: &mut String, s: &Surface) {
  let Some(e) = &s.inbound else {
    return;
  };
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  out.push_str(&format!(
    "  private _subscribe(handlers: Partial<{}InboundHandlers>, partial: boolean): () => void {{\n    return this._gateway.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      switch (inner.{inner_tag}) {{\n",
    s.name, e.outer_disc
  ));
  for iv in s.inbound_event_variants() {
    let invoke = match &iv.payload {
      Some(_) => format!("          handlers.{}?.(event.deviceId, inner.data);", iv.disc),
      None => format!("          handlers.{}?.(event.deviceId);", iv.disc),
    };
    out.push_str(&format!(
      "        case '{}': {{\n{invoke}\n          return;\n        }}\n",
      iv.disc
    ));
  }
  for r in &s.inbound_requests {
    let pass_payload = if r.request_takes_payload {
      ", inner.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "        case '{}': {{\n          if (event.message.meta.kind !== 'request') return;\n          const handler = handlers.{};\n          if (!handler) {{ if (!partial) this._gateway.logger.warn('{}: no handler for inner', '{}'); return; }}\n          const handle = new {}Handle(this._gateway, event.deviceId, event.message.id);\n          const result = handler(handle{pass_payload});\n          if (result && typeof result.then === 'function') {{\n            result.catch((err: unknown) => this._gateway.logger.error('subscribe handler threw:', err));\n          }}\n          return;\n        }}\n",
      r.request_disc, r.request_disc, s.name, r.request_disc, r.request
    ));
  }
  out.push_str(&format!(
    "        default: {{\n          if (!partial) this._gateway.logger.warn('{}: no handler for inner', inner);\n          return;\n        }}\n      }}\n    }});\n  }}\n\n",
    s.name
  ));
  // We need to silence "case fallthrough" / exhaustiveness - for variants
  // that aren't in handlers, the per-case still does `?.()` which is no-op
  // when missing. The `partial` flag controls warning only for default
  // (unknown variant from wire).
  // Note: `case '<variant>'` for variants without handlers still hits its
  // own case (returns early); the warning only fires from `default`.
  // When `partial` is true, *missing* handlers do nothing silently per
  // the optional-chaining `?.`. When `partial` is false, the per-case
  // call still no-ops if undefined; the user contract is to provide all.
  // We intentionally don't enforce no-undefined at runtime - TS does
  // exhaustiveness statically via the `<S>InboundHandlers` type.
  let _ = out;
}

fn push_outbound_methods_gateway(out: &mut String, s: &Surface) {
  let Some(e) = &s.outbound else {
    return;
  };
  let leaf_outbound = e.inner_variants.is_empty();
  let entry_meta = e.category.meta_kind();
  if leaf_outbound && e.outer_payload.is_some() {
    let payload_ts = e.outer_payload.as_ref().map(|p| p.ts()).unwrap();
    let device_arg = if e.unicast { "deviceId: string, " } else { "" };
    let body = if e.unicast {
      format!(
        "    const msg: GatewayToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{entry_meta}' }}, data: {{ type: '{}', data: payload }} }};\n    await this._gateway.send(deviceId, msg, options);",
        e.outer_disc
      )
    } else {
      format!(
        "    const ids = this._gateway.connectedDeviceIds;\n    await Promise.all(ids.map(deviceId => {{\n      const msg: GatewayToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{entry_meta}' }}, data: {{ type: '{}', data: payload }} }};\n      return this._gateway.send(deviceId, msg, options);\n    }}));",
        e.outer_disc
      )
    };
    let doc = if e.unicast {
      format!("Send a `{}` event to a specific peer.", s.name)
    } else {
      format!("Send a `{}` event to every connected peer (broadcast).", s.name)
    };
    out.push_str(&format!(
      "  /** {doc} */\n  async send({device_arg}payload: {payload_ts}, options?: {{ priority?: Priority }}): Promise<void> {{\n{body}\n  }}\n\n"
    ));
    return;
  }
  if leaf_outbound {
    return;
  }
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  for iv in s.outbound_send_variants() {
    let method = camel_first(&iv.variant);
    let payload_param = match &iv.payload {
      Some(p) => format!("payload: {}", p.ts()),
      None => String::new(),
    };
    let inner_object = match &iv.payload {
      Some(_) => format!("{{ {inner_tag}: '{}', data: payload }}", iv.disc),
      None => format!("{{ {inner_tag}: '{}' }}", iv.disc),
    };
    let device_arg = if e.unicast { "deviceId: string" } else { "" };
    let arg_list = match (device_arg.is_empty(), payload_param.is_empty()) {
      (true, true) => "options?: { priority?: Priority }".to_string(),
      (true, false) => format!("{payload_param}, options?: {{ priority?: Priority }}"),
      (false, true) => format!("{device_arg}, options?: {{ priority?: Priority }}"),
      (false, false) => format!("{device_arg}, {payload_param}, options?: {{ priority?: Priority }}"),
    };
    let variant_meta = iv.category.map(|c| c.meta_kind()).unwrap_or(entry_meta);
    let body = if e.unicast {
      format!(
        "    const msg: GatewayToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{variant_meta}' }}, data: {{ type: '{}', data: {inner_object} }} }};\n    await this._gateway.send(deviceId, msg, options);",
        e.outer_disc
      )
    } else {
      format!(
        "    const ids = this._gateway.connectedDeviceIds;\n    await Promise.all(ids.map(deviceId => {{\n      const msg: GatewayToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{variant_meta}' }}, data: {{ type: '{}', data: {inner_object} }} }};\n      return this._gateway.send(deviceId, msg, options);\n    }}));",
        e.outer_disc
      )
    };
    let doc = if e.unicast {
      format!("Send `{}::{}` to a specific peer.", s.name, iv.variant)
    } else {
      format!("Send `{}::{}` to every connected peer (broadcast).", s.name, iv.variant)
    };
    out.push_str(&format!(
      "  /** {doc} */\n  async {method}({arg_list}): Promise<void> {{\n{body}\n  }}\n\n"
    ));
  }
}

fn push_query_methods_gateway(out: &mut String, s: &Surface) {
  for r in &s.outbound_queries {
    push_query_method_gateway(out, r);
  }
}

fn push_query_method_gateway(out: &mut String, r: &TypedRequestEntry) {
  let method = camel_first(&r.request_variant_pascal());
  let req_param = if r.request_takes_payload {
    format!(", req: {}", r.request)
  } else {
    String::new()
  };
  let domain = r.error.as_deref().unwrap_or("never");
  let inner_object = if r.request_takes_payload {
    format!("{{ {}: '{}', data: req }}", r.inner_tag, r.request_disc)
  } else {
    format!("{{ {}: '{}' }}", r.inner_tag, r.request_disc)
  };
  out.push_str(&format!(
    "  /** Typed request to a specific peer: companion sends, daemon responds. */\n  async {method}(deviceId: string{req_param}, options?: {{ timeoutMs?: number }}): Promise<TypedRequestResult<{}, {domain}>> {{\n    const wireData: GatewayToBridgeMsg['data'] = {{ type: '{}', data: {inner_object} }};\n    const response = await this._gateway.request(deviceId, wireData, options?.timeoutMs);\n    const d = response.data;\n    if (d.type === '{}') {{\n      const inner = d.data;\n      if (inner.{} === '{}') return {{ ok: true, response: inner.data }};\n",
    r.response, r.surface_disc, r.surface_disc, r.inner_tag, r.response_disc
  ));
  if let Some(err_disc) = &r.error_disc {
    out.push_str(&format!(
      "      if (inner.{} === '{}') return {{ ok: false, kind: 'domain', error: inner.data }};\n",
      r.inner_tag, err_disc
    ));
  }
  out.push_str("    }\n");
  out.push_str("    if (d.type === 'error') return { ok: false, kind: 'protocol', error: d.data };\n");
  out.push_str("    return { ok: false, kind: 'protocol', error: { type: 'unsupported' } };\n");
  out.push_str("  }\n\n");
}

