//! Swift emitter for surface-namespaced gateway dispatch.
//!
//! Each surface gets two structs:
//! - `<Name>Surface` — gateway-level: cross-peer AsyncStreams, broadcast
//!   sends, typed queries with explicit deviceId parameter.
//! - `<Name>SurfaceForDevice` — per-peer: filtered AsyncStreams, deviceId
//!   baked into sends and queries.
//!
//! `gateway.<surface>` is a nonisolated extension property returning a
//! fresh struct; `gateway.device(_:)` returns a `BridgethingGatewayDevice`
//! proxy whose surfaces are device-scoped.

use std::path::Path;

use anyhow::{Context, Result};

use super::plan::{EntryCategory, Plan, Surface, TypedRequestEntry, rename_camel, surfaces};

/// Wrap an identifier in backticks if it collides with a Swift keyword.
/// Used for codegen-emitted method/property names that come from wire
/// discriminators (e.g. `repeat`).
fn swift_ident(s: &str) -> String {
  match s {
    "associatedtype" | "class" | "deinit" | "enum" | "extension" | "fileprivate" | "func" | "import" | "init"
    | "inout" | "internal" | "let" | "open" | "operator" | "private" | "protocol" | "public" | "rethrows"
    | "static" | "struct" | "subscript" | "typealias" | "var" | "break" | "case" | "continue" | "default" | "defer"
    | "do" | "else" | "fallthrough" | "for" | "guard" | "if" | "in" | "repeat" | "return" | "switch" | "where"
    | "while" | "as" | "Any" | "catch" | "false" | "is" | "nil" | "super" | "self" | "Self" | "throw" | "throws"
    | "true" | "try" | "Type" | "Protocol" => format!("`{s}`"),
    _ => s.to_string(),
  }
}

const SWIFT_OUTPUT: &str = "packages/gateway/swift/Sources/BridgethingGateway/Dispatch+Generated.swift";

pub fn emit_swift(plan: &Plan) -> Result<()> {
  let surfaces = surfaces(plan);
  let mut out = String::new();
  out.push_str("// THIS FILE IS GENERATED BY tools/codegen. Do not edit by hand.\n");
  out.push_str("// Re-generate with `just codegen` (or `just swift`).\n\n");
  out.push_str("import BridgethingSchema\n");
  out.push_str("import Foundation\n\n");

  if !plan.outbound_requests.is_empty() || !plan.inbound_requests.is_empty() {
    out.push_str(&swift_request_result_enum());
  }

  for s in &surfaces {
    push_gateway_surface_struct(&mut out, s);
  }

  for s in &surfaces {
    push_device_surface_struct(&mut out, s);
  }

  push_device_proxy_struct(&mut out, &surfaces);

  out.push_str("extension BridgethingGateway {\n");
  for s in &surfaces {
    out.push_str(&format!(
      "  /// Methods scoped to the `{}` wire surface.\n  public nonisolated var {}: {}Surface {{ {}Surface(gateway: self) }}\n",
      s.name, s.prop, s.name, s.name
    ));
  }
  out.push_str(
    "  /// Returns a per-device proxy with `deviceId` baked into every method and stream.\n  public nonisolated func device(_ deviceId: String) -> BridgethingGatewayDevice {\n    BridgethingGatewayDevice(gateway: self, deviceId: deviceId)\n  }\n}\n\n",
  );

  for s in &surfaces {
    for r in &s.inbound_requests {
      out.push_str(&swift_request_handle_class(r));
    }
  }

  std::fs::create_dir_all(Path::new(SWIFT_OUTPUT).parent().unwrap()).context("ensure swift dispatch dir")?;
  std::fs::write(SWIFT_OUTPUT, out).context("write swift dispatch")?;
  Ok(())
}

fn swift_request_result_enum() -> String {
  r#"public enum RequestResult<R: Sendable, E: Sendable>: Sendable {
  case ok(R)
  case domain(E)
  case protocolError(GatewayError)
}

"#
  .to_string()
}

