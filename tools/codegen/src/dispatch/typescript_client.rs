//! TypeScript emitter for the on-device webapp client SDK.
//!
//! Output shape mirrors the gateway emitter but stripped of the
//! multi-peer machinery (no device proxy, no broadcast). The local
//! WebSocket protocol always has exactly one peer (the daemon), so
//! every `on*` listener and outbound send is implicitly addressed.

use std::{collections::BTreeSet, path::Path};

use anyhow::{Context, Result};

use super::{
  inventory::PayloadType,
  plan::{Plan, Surface, TypedRequestEntry, surfaces},
};

const TS_OUTPUT: &str = "packages/client-ts/src/dispatch.generated.ts";

pub fn emit_typescript_client(plan: &Plan) -> Result<()> {
  let surfaces = surfaces(plan);
  let mut out = String::new();
  push_header(&mut out);
  push_imports(&mut out, &surfaces);
  push_typed_request_result(&mut out);

  for s in &surfaces {
    push_inbound_handlers_types(&mut out, s);
  }

  for s in &surfaces {
    push_surface_class(&mut out, s);
  }

  push_outer_handlers_types(&mut out, &surfaces);

  push_module_augmentation(&mut out, &surfaces);

  for s in &surfaces {
    for r in &s.inbound_requests {
      push_request_handle_class(&mut out, r);
    }
  }

  push_apply_dispatch(&mut out, &surfaces);

  std::fs::create_dir_all(Path::new(TS_OUTPUT).parent().unwrap()).context("ensure client-ts dispatch dir")?;
  std::fs::write(TS_OUTPUT, out).context("write client-ts dispatch")?;
  Ok(())
}

fn push_header(out: &mut String) {
  out.push_str("// THIS FILE IS GENERATED BY tools/codegen. Do not edit by hand.\n");
  out.push_str("// Re-generate with `just codegen` (or `just typescript`).\n\n");
}

fn push_imports(out: &mut String, surfaces: &[Surface]) {
  let mut imports: BTreeSet<String> = BTreeSet::new();
  for s in surfaces {
    if let Some(e) = &s.inbound {
      if let Some(PayloadType::Named(n)) = &e.outer_payload {
        imports.insert(n.clone());
      }
      for iv in &e.inner_variants {
        if let Some(PayloadType::Named(n)) = &iv.payload {
          imports.insert(n.clone());
        }
      }
    }
    if let Some(e) = &s.outbound {
      if let Some(PayloadType::Named(n)) = &e.outer_payload {
        imports.insert(n.clone());
      }
      for iv in &e.inner_variants {
        if let Some(PayloadType::Named(n)) = &iv.payload {
          imports.insert(n.clone());
        }
      }
    }
    for r in s.outbound_queries.iter().chain(&s.inbound_requests) {
      if r.request_takes_payload {
        imports.insert(r.request.clone());
      }
      imports.insert(r.response.clone());
      if let Some(e) = &r.error {
        imports.insert(e.clone());
      }
    }
  }
  imports.insert("BridgeToClientMsg".to_string());
  imports.insert("ClientToBridgeMsg".to_string());
  imports.insert("WireError".to_string());

  out.push_str("import {\n");
  for name in &imports {
    out.push_str(&format!("  type {name},\n"));
  }
  out.push_str("  newUuid,\n");
  out.push_str("} from '@bridgething/lib';\n");
  out.push_str("import { BridgethingClient, type ClientEvent } from './index';\n\n");
}

fn push_typed_request_result(out: &mut String) {
  out.push_str(
    "export type TypedRequestResult<R, E> =\n  | { ok: true; response: R }\n  | { ok: false; kind: 'domain'; error: E }\n  | { ok: false; kind: 'protocol'; error: WireError };\n\n",
  );
}

fn push_inbound_handlers_types(out: &mut String, s: &Surface) {
  let entries = inbound_handler_entries(s);
  if entries.len() < 2 {
    return;
  }
  out.push_str(&format!("export type {}InboundHandlers = {{\n", s.name));
  for (k, sig) in &entries {
    out.push_str(&format!("  {k}: {sig};\n"));
  }
  out.push_str("};\n\n");
}

fn inbound_handler_entries(s: &Surface) -> Vec<(String, String)> {
  let mut keys: Vec<(String, String)> = Vec::new();
  for iv in s.inbound_event_variants() {
    let sig = match &iv.payload {
      Some(p) => format!("(msg: {}) => void", p.ts()),
      None => "() => void".to_string(),
    };
    keys.push((iv.disc.clone(), sig));
  }
  for r in &s.inbound_requests {
    let payload_arg = if r.request_takes_payload {
      format!(", req: {}", r.request)
    } else {
      String::new()
    };
    let sig = format!("(handle: {}Handle{payload_arg}) => Promise<void> | void", r.request);
    keys.push((r.request_disc.clone(), sig));
  }
  keys
}

fn push_surface_class(out: &mut String, s: &Surface) {
  out.push_str(&format!("export class {}Surface {{\n", s.name));
  out.push_str("  constructor(private readonly _client: BridgethingClient) {}\n\n");

  push_inbound_methods(out, s);
  push_subscribe_methods(out, s);
  push_outbound_methods(out, s);
  push_query_methods(out, s);

  out.push_str("}\n\n");
}

fn push_inbound_methods(out: &mut String, s: &Surface) {
  let Some(e) = &s.inbound else {
    for r in &s.inbound_requests {
      push_request_handler_method(out, r);
    }
    return;
  };
  let leaf_inbound = e.inner_variants.is_empty();
  if leaf_inbound && e.outer_payload.is_some() {
    let payload_ts = e.outer_payload.as_ref().map(|p| p.ts()).unwrap();
    out.push_str(&format!(
      "  /** Subscribe to `{}` messages from the daemon. */\n  on(handler: (msg: {payload_ts}) => void): () => void {{\n    return this._client.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      handler(data.data);\n    }});\n  }}\n\n",
      s.name, e.outer_disc
    ));
    return;
  }
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  for iv in s.inbound_event_variants() {
    let method = format!("on{}", iv.variant);
    let sig = match &iv.payload {
      Some(p) => format!("(msg: {}) => void", p.ts()),
      None => "() => void".to_string(),
    };
    let invoke = match &iv.payload {
      Some(_) => "handler(inner.data);",
      None => "handler();",
    };
    out.push_str(&format!(
      "  /** Subscribe to `{}::{}` from the daemon. */\n  {method}(handler: {sig}): () => void {{\n    return this._client.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      if (inner.{inner_tag} !== '{}') return;\n      {invoke}\n    }});\n  }}\n\n",
      s.name, iv.variant, e.outer_disc, iv.disc
    ));
  }
  for r in &s.inbound_requests {
    push_request_handler_method(out, r);
  }
}

fn push_request_handler_method(out: &mut String, r: &TypedRequestEntry) {
  let payload_arg = if r.request_takes_payload {
    format!(", req: {}", r.request)
  } else {
    String::new()
  };
  let pass_payload = if r.request_takes_payload {
    ", inner.data".to_string()
  } else {
    String::new()
  };
  let method = format!("on{}", r.request_variant_pascal());
  out.push_str(&format!(
    "  /** Typed inbound `{}` request from the daemon: handler is given a typed handle for the response. */\n  {method}(handler: (handle: {}Handle{payload_arg}) => Promise<void> | void): () => void {{\n    return this._client.on(event => {{\n      if (event.type !== 'message') return;\n      const message = event.message;\n      if (message.meta.kind !== 'request') return;\n      const data = message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      if (inner.{} !== '{}') return;\n      const handle = new {}Handle(this._client, message.id);\n      const result = handler(handle{pass_payload});\n      if (result && typeof result.then === 'function') {{\n        result.catch((err: unknown) => {{ this._client.logger.error('on{} handler threw:', err); }});\n      }}\n    }});\n  }}\n\n",
    r.request, r.request, r.surface_disc, r.inner_tag, r.request_disc, r.request, r.request_variant_pascal()
  ));
}

fn push_subscribe_methods(out: &mut String, s: &Surface) {
  let total_inbound = s.inbound_event_variants().len() + s.inbound_requests.len();
  if total_inbound < 2 {
    return;
  }
  out.push_str(&format!(
    "  /** Exhaustive subscribe over all inbound `{}` variants. */\n  subscribe(handlers: {}InboundHandlers): () => void {{\n    return this._subscribe(handlers, false);\n  }}\n\n",
    s.name, s.name
  ));
  out.push_str(&format!(
    "  /** Same as `subscribe` but every handler is optional. */\n  subscribePartial(handlers: Partial<{}InboundHandlers>): () => void {{\n    return this._subscribe(handlers, true);\n  }}\n\n",
    s.name
  ));
  push_subscribe_impl(out, s);
}

fn push_subscribe_impl(out: &mut String, s: &Surface) {
  let Some(e) = &s.inbound else {
    return;
  };
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  out.push_str(&format!(
    "  private _subscribe(handlers: Partial<{}InboundHandlers>, partial: boolean): () => void {{\n    return this._client.on(event => {{\n      if (event.type !== 'message') return;\n      const data = event.message.data;\n      if (data.type !== '{}') return;\n      const inner = data.data;\n      switch (inner.{inner_tag}) {{\n",
    s.name, e.outer_disc
  ));
  for iv in s.inbound_event_variants() {
    let invoke = match &iv.payload {
      Some(_) => format!("          handlers.{}?.(inner.data);", iv.disc),
      None => format!("          handlers.{}?.();", iv.disc),
    };
    out.push_str(&format!(
      "        case '{}': {{\n{invoke}\n          return;\n        }}\n",
      iv.disc
    ));
  }
  for r in &s.inbound_requests {
    let pass_payload = if r.request_takes_payload {
      ", inner.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "        case '{}': {{\n          if (event.message.meta.kind !== 'request') return;\n          const handler = handlers.{};\n          if (!handler) {{ if (!partial) this._client.logger.warn('{}: no handler for inner', '{}'); return; }}\n          const handle = new {}Handle(this._client, event.message.id);\n          const result = handler(handle{pass_payload});\n          if (result && typeof result.then === 'function') {{\n            result.catch((err: unknown) => this._client.logger.error('subscribe handler threw:', err));\n          }}\n          return;\n        }}\n",
      r.request_disc, r.request_disc, s.name, r.request_disc, r.request
    ));
  }
  out.push_str(&format!(
    "        default: {{\n          if (!partial) this._client.logger.warn('{}: no handler for inner', inner);\n          return;\n        }}\n      }}\n    }});\n  }}\n\n",
    s.name
  ));
}

fn push_outbound_methods(out: &mut String, s: &Surface) {
  let Some(e) = &s.outbound else {
    return;
  };
  let leaf_outbound = e.inner_variants.is_empty();
  let entry_meta = e.category.meta_kind();
  if leaf_outbound && e.outer_payload.is_some() {
    let payload_ts = e.outer_payload.as_ref().map(|p| p.ts()).unwrap();
    out.push_str(&format!(
      "  /** Send a `{}` event to the daemon. */\n  async send(payload: {payload_ts}): Promise<void> {{\n    const msg: ClientToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{entry_meta}' }}, data: {{ type: '{}', data: payload }} }};\n    await this._client.send(msg);\n  }}\n\n",
      s.name, e.outer_disc
    ));
    return;
  }
  if leaf_outbound {
    return;
  }
  let inner_tag = e.inner_tag_field.as_deref().unwrap_or("event");
  for iv in s.outbound_send_variants() {
    let method = camel_first(&iv.variant);
    let arg_list = match &iv.payload {
      Some(p) => format!("payload: {}", p.ts()),
      None => String::new(),
    };
    let inner_object = match &iv.payload {
      Some(_) => format!("{{ {inner_tag}: '{}', data: payload }}", iv.disc),
      None => format!("{{ {inner_tag}: '{}' }}", iv.disc),
    };
    let variant_meta = iv.category.map(|c| c.meta_kind()).unwrap_or(entry_meta);
    out.push_str(&format!(
      "  /** Send `{}::{}` to the daemon. */\n  async {method}({arg_list}): Promise<void> {{\n    const msg: ClientToBridgeMsg = {{ id: newUuid(), meta: {{ kind: '{variant_meta}' }}, data: {{ type: '{}', data: {inner_object} }} }};\n    await this._client.send(msg);\n  }}\n\n",
      s.name, iv.variant, e.outer_disc
    ));
  }
}

fn push_query_methods(out: &mut String, s: &Surface) {
  for r in &s.outbound_queries {
    push_query_method(out, r);
  }
}

fn push_query_method(out: &mut String, r: &TypedRequestEntry) {
  let method = camel_first(&r.request_variant_pascal());
  let req_param = if r.request_takes_payload {
    format!("req: {}", r.request)
  } else {
    String::new()
  };
  let domain = r.error.as_deref().unwrap_or("never");
  let inner_object = if r.request_takes_payload {
    format!("{{ {}: '{}', data: req }}", r.inner_tag, r.request_disc)
  } else {
    format!("{{ {}: '{}' }}", r.inner_tag, r.request_disc)
  };
  let opts_param = if req_param.is_empty() {
    "options?: { timeoutMs?: number }".to_string()
  } else {
    format!("{req_param}, options?: {{ timeoutMs?: number }}")
  };
  out.push_str(&format!(
    "  /** Typed request to the daemon: webapp sends, daemon responds. */\n  async {method}({opts_param}): Promise<TypedRequestResult<{}, {domain}>> {{\n    const wireData: ClientToBridgeMsg['data'] = {{ type: '{}', data: {inner_object} }};\n    const response = await this._client.request(wireData, options?.timeoutMs);\n    const d = response.data;\n    if (d.type === '{}') {{\n      const inner = d.data;\n      if (inner.{} === '{}') return {{ ok: true, response: inner.data }};\n",
    r.response, r.surface_disc, r.surface_disc, r.inner_tag, r.response_disc
  ));
  if let Some(err_disc) = &r.error_disc {
    out.push_str(&format!(
      "      if (inner.{} === '{}') return {{ ok: false, kind: 'domain', error: inner.data }};\n",
      r.inner_tag, err_disc
    ));
  }
  out.push_str("    }\n");
  out.push_str("    if (d.type === 'error') return { ok: false, kind: 'protocol', error: d.data };\n");
  out.push_str("    return { ok: false, kind: 'protocol', error: { type: 'unsupported' } };\n");
  out.push_str("  }\n\n");
}

fn push_outer_handlers_types(out: &mut String, surfaces: &[Surface]) {
  out.push_str("export type ClientMessageHandlers = {\n");
  for s in surfaces {
    if let Some(value) = outer_value(s) {
      out.push_str(&format!("  {}: {value};\n", s.prop));
    }
  }
  out.push_str("};\n\n");

  out.push_str("export type PartialClientMessageHandlers = {\n");
  for s in surfaces {
    if let Some(value) = outer_value(s) {
      let partial = partialize(&value);
      out.push_str(&format!("  {}?: {partial};\n", s.prop));
    }
  }
  out.push_str("};\n\n");
}

fn outer_value(s: &Surface) -> Option<String> {
  let has_event_inner = !s.inbound_event_variants().is_empty();
  let has_typed_req = !s.inbound_requests.is_empty();
  if !has_event_inner && !has_typed_req {
    return None;
  }
  if let Some(e) = &s.inbound
    && e.inner_variants.is_empty()
    && e.outer_payload.is_some()
    && !has_typed_req
  {
    let p = e.outer_payload.as_ref().map(|p| p.ts()).unwrap();
    return Some(format!("(msg: {p}) => void"));
  }
  if !has_event_inner && s.inbound_requests.len() == 1 {
    let r = &s.inbound_requests[0];
    let payload_arg = if r.request_takes_payload {
      format!(", req: {}", r.request)
    } else {
      String::new()
    };
    return Some(format!(
      "(handle: {}Handle{payload_arg}) => Promise<void> | void",
      r.request
    ));
  }
  Some(format!("{}InboundHandlers", s.name))
}

fn partialize(ty: &str) -> String {
  if ty.starts_with('(') {
    ty.to_string()
  } else {
    format!("Partial<{ty}>")
  }
}

fn push_module_augmentation(out: &mut String, surfaces: &[Surface]) {
  out.push_str("declare module './index' {\n");
  out.push_str("  interface BridgethingClient {\n");
  for s in surfaces {
    out.push_str(&format!(
      "    /** Methods scoped to the `{}` wire surface. */\n    readonly {}: {}Surface;\n",
      s.name, s.prop, s.name
    ));
  }
  out.push_str("    /** Exhaustive subscribe across every inbound wire surface. */\n");
  out.push_str("    subscribe(handlers: ClientMessageHandlers): () => void;\n");
  out.push_str("    subscribePartial(handlers: PartialClientMessageHandlers): () => void;\n");
  out.push_str("  }\n}\n\n");
}

fn push_request_handle_class(out: &mut String, r: &TypedRequestEntry) {
  out.push_str(&format!(
    "export class {}Handle {{\n  constructor(\n    private readonly _client: BridgethingClient,\n    public readonly requestId: string,\n  ) {{}}\n\n",
    r.request
  ));
  out.push_str(&format!(
    "  async respond(response: {}): Promise<void> {{\n    const msg: ClientToBridgeMsg = {{ id: newUuid(), meta: {{ kind: 'response', data: {{ requestId: this.requestId }} }}, data: {{ type: '{}', data: {{ {}: '{}', data: response }} }} }};\n    await this._client.send(msg);\n  }}\n\n",
    r.response, r.surface_disc, r.inner_tag, r.response_disc
  ));
  if let (Some(err_type), Some(err_disc)) = (&r.error, &r.error_disc) {
    out.push_str(&format!(
      "  async respondErr(error: {err_type}): Promise<void> {{\n    const msg: ClientToBridgeMsg = {{ id: newUuid(), meta: {{ kind: 'response', data: {{ requestId: this.requestId }} }}, data: {{ type: '{}', data: {{ {}: '{}', data: error }} }} }};\n    await this._client.send(msg);\n  }}\n\n",
      r.surface_disc, r.inner_tag, err_disc
    ));
  }
  out.push_str("  async respondProtocolErr(error: WireError): Promise<void> {\n    const msg: ClientToBridgeMsg = { id: newUuid(), meta: { kind: 'response', data: { requestId: this.requestId } }, data: { type: 'error', data: error } };\n    await this._client.send(msg);\n  }\n");
  out.push_str("}\n\n");
}

fn push_apply_dispatch(out: &mut String, surfaces: &[Surface]) {
  out.push_str("type ClientSurfaceCache = {\n");
  for s in surfaces {
    out.push_str(&format!("  {}?: {}Surface;\n", s.prop, s.name));
  }
  out.push_str("};\n\n");

  out.push_str("/**\n * Apply codegen-emitted prototype augmentations to BridgethingClient.\n * Called once from `index.ts` after the class definition. Idempotent.\n */\nexport function applyDispatch(): void {\n");
  out.push_str("  const surfaceCache = new WeakMap<BridgethingClient, ClientSurfaceCache>();\n");
  out.push_str("  function bucketFor(c: BridgethingClient): ClientSurfaceCache {\n    let bucket = surfaceCache.get(c);\n    if (!bucket) { bucket = {}; surfaceCache.set(c, bucket); }\n    return bucket;\n  }\n\n");
  for s in surfaces {
    out.push_str(&format!(
      "  Object.defineProperty(BridgethingClient.prototype, '{}', {{\n    configurable: true,\n    enumerable: true,\n    get(this: BridgethingClient): {}Surface {{\n      const bucket = bucketFor(this);\n      return (bucket.{} ??= new {}Surface(this));\n    }},\n  }});\n",
      s.prop, s.name, s.prop, s.name
    ));
  }
  out.push('\n');

  out.push_str("  BridgethingClient.prototype.subscribe = function (handlers: ClientMessageHandlers): () => void {\n    return outerSubscribe(this, handlers, false);\n  };\n");
  out.push_str("  BridgethingClient.prototype.subscribePartial = function (handlers: PartialClientMessageHandlers): () => void {\n    return outerSubscribe(this, handlers, true);\n  };\n");
  out.push_str("}\n\n");

  push_outer_subscribe(out, surfaces);
}

fn push_outer_subscribe(out: &mut String, surfaces: &[Surface]) {
  out.push_str("function outerSubscribe(c: BridgethingClient, handlers: PartialClientMessageHandlers, partial: boolean): () => void {\n  return c.on((event: ClientEvent) => {\n    if (event.type !== 'message') return;\n    const data = event.message.data;\n    switch (data.type) {\n");
  for s in surfaces {
    push_outer_case(out, s);
  }
  out.push_str("      default: {\n        if (!partial) c.logger.warn('subscribe: no handler for unknown wire variant', data);\n        return;\n      }\n    }\n  });\n}\n\n");
}

fn push_outer_case(out: &mut String, s: &Surface) {
  if outer_value(s).is_none() {
    return;
  }
  let prop = &s.prop;
  let leaf_only = s
    .inbound
    .as_ref()
    .map(|e| e.inner_variants.is_empty() && e.outer_payload.is_some())
    .unwrap_or(false);
  let has_typed_req = !s.inbound_requests.is_empty();
  let single_request_only = s.inbound_event_variants().is_empty() && s.inbound_requests.len() == 1;
  if leaf_only && !has_typed_req {
    out.push_str(&format!(
      "      case '{prop}': {{\n        const handler = handlers.{prop};\n        if (!handler) {{ if (!partial) c.logger.warn('subscribe: no handler for {prop}'); return; }}\n        handler(data.data);\n        return;\n      }}\n"
    ));
    return;
  }
  if single_request_only {
    let r = &s.inbound_requests[0];
    let payload_pass = if r.request_takes_payload {
      ", data.data.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "      case '{prop}': {{\n        if (event.message.meta.kind !== 'request') return;\n        const handler = handlers.{prop};\n        if (!handler) {{ if (!partial) c.logger.warn('subscribe: no handler for {prop}'); return; }}\n        const handle = new {}Handle(c, event.message.id);\n        const result = handler(handle{payload_pass});\n        if (result && typeof result.then === 'function') result.catch((err: unknown) => c.logger.error('subscribe handler threw:', err));\n        return;\n      }}\n",
      r.request
    ));
    return;
  }
  let inner_tag = s
    .inbound
    .as_ref()
    .and_then(|e| e.inner_tag_field.as_deref())
    .unwrap_or("event");
  out.push_str(&format!(
    "      case '{prop}': {{\n        const innerHandlers = handlers.{prop};\n        if (!innerHandlers) {{ if (!partial) c.logger.warn('subscribe: no handler for {prop}'); return; }}\n        const inner = data.data;\n        switch (inner.{inner_tag}) {{\n"
  ));
  for iv in s.inbound_event_variants() {
    let invoke = match &iv.payload {
      Some(_) => format!("            innerHandlers.{}?.(inner.data);", iv.disc),
      None => format!("            innerHandlers.{}?.();", iv.disc),
    };
    out.push_str(&format!(
      "          case '{}': {{\n{invoke}\n            return;\n          }}\n",
      iv.disc
    ));
  }
  for r in &s.inbound_requests {
    let pass_payload = if r.request_takes_payload {
      ", inner.data".to_string()
    } else {
      String::new()
    };
    out.push_str(&format!(
      "          case '{}': {{\n            if (event.message.meta.kind !== 'request') return;\n            const handler = innerHandlers.{};\n            if (!handler) {{ if (!partial) c.logger.warn('{}: no handler for inner', '{}'); return; }}\n            const handle = new {}Handle(c, event.message.id);\n            const result = handler(handle{pass_payload});\n            if (result && typeof result.then === 'function') result.catch((err: unknown) => c.logger.error('subscribe handler threw:', err));\n            return;\n          }}\n",
      r.request_disc, r.request_disc, s.name, r.request_disc, r.request
    ));
  }
  out.push_str(&format!(
    "          default: {{\n            if (!partial) c.logger.warn('{}: no handler for inner', inner);\n            return;\n          }}\n        }}\n      }}\n",
    s.name
  ));
}

fn camel_first(s: &str) -> String {
  let mut chars = s.chars();
  let mut out = String::new();
  if let Some(c) = chars.next() {
    out.extend(c.to_lowercase());
  }
  out.extend(chars);
  out
}
