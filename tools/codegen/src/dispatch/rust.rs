//! Rust SDK surface emitter. Unlike the TS/Swift/Kotlin emitters - which
//! must materialize DTOs and per-op logic in a foreign language - the
//! Rust surface is pure naming sugar over the generic runtime
//! (`bridgething-sdk-runtime`). Every emitted method is a one-line
//! delegation to `command` / `event` / `request` (outbound) or a typed
//! filter over the runtime event broadcast (inbound), and is type-checked
//! against the real `libbridgething` wire types at compile time. A bug in
//! this emitter is therefore a build failure in the SDK crate, never a
//! latent runtime mismatch.

use anyhow::{Context, Result};

use super::{
  inventory::PayloadType,
  plan::{DispatchEntry, EntryCategory, InnerVariantPlan, Plan, Surface, surfaces},
};

/// Per-protocol output binding.
pub struct RustTarget {
  /// Output file (under the SDK crate's `src/`).
  pub out_path: &'static str,
  /// SDK handle type the surface accessors hang off (`Client` / `Gateway`).
  pub sdk_type: &'static str,
  /// `libbridgething` submodule whose wire types this protocol uses.
  pub wire_mod: &'static str,
}

pub fn emit_rust(plan: &Plan, target: &RustTarget) -> Result<()> {
  let surfaces = surfaces(plan);
  let in_data = plan.protocol.inbound_direction().wire_data_name();
  let mut out = String::new();

  out.push_str("// THIS FILE IS GENERATED BY tools/codegen. Do not edit by hand.\n");
  out.push_str("// Re-generate with `just codegen` (or `just rust`).\n\n");
  out.push_str("use bridgething_sdk_runtime::{RequestFailure, SdkError};\n");
  out.push_str("use futures::{future::ready, Stream, StreamExt};\n");
  out.push_str("use tokio_stream::wrappers::BroadcastStream;\n");
  out.push_str(&format!("use libbridgething::{{{}::*, *}};\n", target.wire_mod));
  out.push_str(&format!("use crate::{};\n\n", target.sdk_type));

  let active: Vec<&Surface> = surfaces.iter().filter(|s| surface_has_any(s)).collect();

  out.push_str(&format!("impl {} {{\n", target.sdk_type));
  for s in &active {
    out.push_str(&format!(
      "  /// The `{name}` surface.\n  pub fn {accessor}(&self) -> {name}Surface<'_> {{\n    {name}Surface(self)\n  }}\n",
      name = s.name,
      accessor = snake(&s.name),
    ));
  }
  out.push_str("}\n\n");

  for s in &active {
    out.push_str(&format!(
      "/// Methods scoped to the `{name}` wire surface.\npub struct {name}Surface<'a>(&'a {sdk});\n\nimpl<'a> {name}Surface<'a> {{\n",
      name = s.name,
      sdk = target.sdk_type,
    ));
    emit_outbound_sends(&mut out, s);
    emit_outbound_queries(&mut out, s);
    emit_inbound_events(&mut out, s, in_data);
    out.push_str("}\n\n");
  }

  std::fs::write(target.out_path, out).with_context(|| format!("write {}", target.out_path))?;
  Ok(())
}

fn surface_has_any(s: &Surface) -> bool {
  !emittable_sends(s).is_empty() || !s.outbound_queries.is_empty() || inbound_has_events(s)
}

/// Outbound variants we can actually emit a method for: a send variant
/// must carry an Event/Command tag (its bucket sibling enum exists).
/// Untagged variants (e.g. `ForwardMessage`'s adjacent-tagged arms,
/// reachable via the generic `event`) are excluded so a surface left
/// with nothing is skipped rather than emitting an empty struct.
fn emittable_sends(s: &Surface) -> Vec<&InnerVariantPlan> {
  s.outbound_send_variants()
    .into_iter()
    .filter(|iv| matches!(iv.category, Some(EntryCategory::Command | EntryCategory::Event)))
    .collect()
}

/// True when the inbound parent enum has at least one `#[bridge_event]`
/// variant - i.e. `BridgeEnum` emitted an `into_event()` we can narrow
/// through. Response/request-only surfaces have no event stream.
fn inbound_has_events(s: &Surface) -> bool {
  s.inbound
    .as_ref()
    .map(|e| {
      e.inner_variants
        .iter()
        .any(|iv| iv.category == Some(EntryCategory::Event))
    })
    .unwrap_or(false)
}

fn outer_payload_name(entry: Option<&DispatchEntry>) -> Option<&str> {
  match entry?.outer_payload.as_ref()? {
    PayloadType::Named(n) => Some(n),
    _ => None,
  }
}

fn emit_outbound_sends(out: &mut String, s: &Surface) {
  let Some(parent) = outer_payload_name(s.outbound.as_ref()) else {
    return;
  };
  for iv in emittable_sends(s) {
    let (suffix, verb) = match iv.category {
      Some(EntryCategory::Command) => ("Command", "command"),
      Some(EntryCategory::Event) => ("Event", "event"),
      _ => continue,
    };
    let sibling = format!("{parent}{suffix}");
    let method = snake(&iv.variant);
    match &iv.payload {
      None => out.push_str(&format!(
        "  pub async fn {method}(&self) -> Result<(), SdkError> {{\n    self.0.{verb}({sibling}::{variant}).await\n  }}\n",
        variant = iv.variant,
      )),
      Some(payload) => out.push_str(&format!(
        "  pub async fn {method}(&self, payload: {ty}) -> Result<(), SdkError> {{\n    self.0.{verb}({sibling}::{variant}(payload)).await\n  }}\n",
        ty = payload_rust(payload),
        variant = iv.variant,
      )),
    }
  }
}

fn emit_outbound_queries(out: &mut String, s: &Surface) {
  for q in &s.outbound_queries {
    let method = snake(&q.request_variant_pascal());
    let response = &q.response;
    let error = q
      .error
      .clone()
      .unwrap_or_else(|| "::core::convert::Infallible".to_string());
    if q.request_takes_payload {
      out.push_str(&format!(
        "  pub async fn {method}(&self, request: {req}) -> Result<{response}, RequestFailure<{error}>> {{\n    self.0.request(request).await\n  }}\n",
        req = q.request,
      ));
    } else {
      out.push_str(&format!(
        "  pub async fn {method}(&self) -> Result<{response}, RequestFailure<{error}>> {{\n    self.0.request({req}).await\n  }}\n",
        req = q.request,
      ));
    }
  }
}

fn emit_inbound_events(out: &mut String, s: &Surface, in_data: &str) {
  if !inbound_has_events(s) {
    return;
  }
  let Some(parent) = outer_payload_name(s.inbound.as_ref()) else {
    return;
  };
  out.push_str(&format!(
    "  /// Stream of `{name}` events.\n  pub fn events(&self) -> impl Stream<Item = {parent}Event> + 'static {{\n    BroadcastStream::new(self.0.events()).filter_map(|msg| {{\n      ready(match msg {{\n        Ok(msg) => match msg.data {{\n          {in_data}::{variant}(inner) => inner.into_event(),\n          _ => None,\n        }},\n        Err(_) => None,\n      }})\n    }})\n  }}\n",
    name = s.name,
    variant = s.name,
  ));
}

fn payload_rust(p: &PayloadType) -> String {
  match p {
    PayloadType::Named(n) => n.clone(),
    PayloadType::Bytes => "Vec<u8>".to_string(),
    PayloadType::JsonValue => "serde_json::Value".to_string(),
    PayloadType::StringScalar => "String".to_string(),
  }
}

/// PascalCase -> snake_case, escaping Rust keywords as raw identifiers.
fn snake(pascal: &str) -> String {
  let chars: Vec<char> = pascal.chars().collect();
  let mut out = String::new();
  for (i, ch) in chars.iter().enumerate() {
    if ch.is_uppercase() {
      let prev_lower = i > 0 && chars[i - 1].is_lowercase();
      let next_lower = i + 1 < chars.len() && chars[i + 1].is_lowercase();
      if i > 0 && (prev_lower || next_lower) {
        out.push('_');
      }
      out.extend(ch.to_lowercase());
    } else {
      out.push(*ch);
    }
  }
  if is_keyword(&out) { format!("r#{out}") } else { out }
}

fn is_keyword(s: &str) -> bool {
  matches!(
    s,
    "as"
      | "break"
      | "const"
      | "continue"
      | "crate"
      | "else"
      | "enum"
      | "extern"
      | "false"
      | "fn"
      | "for"
      | "if"
      | "impl"
      | "in"
      | "let"
      | "loop"
      | "match"
      | "mod"
      | "move"
      | "mut"
      | "pub"
      | "ref"
      | "return"
      | "self"
      | "static"
      | "struct"
      | "super"
      | "trait"
      | "true"
      | "type"
      | "unsafe"
      | "use"
      | "where"
      | "while"
      | "async"
      | "await"
      | "dyn"
  )
}
