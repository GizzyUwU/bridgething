const ENVELOPE_TRAIT: &str = "EnvelopeHandler";

struct InboundArm<'a> {
  outer: &'a WireVariant,
  inner: Option<&'a EnumDef>,
  surface: Option<&'a Surface>,
}

impl<'a> InboundArm<'a> {
  fn prop(&self) -> String {
    rename_camel(&self.outer.name)
  }

  fn requests(&self) -> &'a [TypedRequestEntry] {
    self.surface.map(|s| s.inbound_requests.as_slice()).unwrap_or_default()
  }

  fn dispatched(&self) -> Vec<&'a WireVariant> {
    let Some(inner) = self.inner else { return Vec::new() };
    inner
      .variants
      .iter()
      .filter(|v| {
        self
          .surface
          .is_none_or(|s| !s.is_inbound_request_variant(&v.name, v.payload.as_ref()))
      })
      .collect()
  }
}

fn handler_trait(surface: &str) -> String {
  format!("{surface}Handler")
}

fn inbound_arms<'a>(wire: &'a EnumDef, inv: &'a Inventory, all: &'a [Surface], direction: &str) -> Vec<InboundArm<'a>> {
  wire
    .variants
    .iter()
    .map(|outer| InboundArm {
      outer,
      inner: dispatch_enum(inv, outer, direction),
      surface: all.iter().find(|s| s.name == outer.name),
    })
    .collect()
}

fn dispatch_enum<'a>(inv: &'a Inventory, outer: &WireVariant, direction: &str) -> Option<&'a EnumDef> {
  let PayloadType::Named(name) = outer.payload.as_ref()? else {
    return None;
  };
  let conventional = *name == format!("{direction}{}Msg", outer.name);
  (conventional || inv.markers.contains_key(name)).then(|| inv.enums.get(name))?
}

fn emit_handlers(out: &mut String, plan: &Plan, inv: &Inventory, all: &[Surface], protocol: &str) -> Result<()> {
  let in_data = plan.protocol.inbound_direction().wire_data_name();
  let in_msg = in_data.trim_end_matches("Data");
  let wire = inv
    .wire_enums
    .get(in_data)
    .ok_or_else(|| anyhow!("rust dispatch: missing wire enum {in_data}"))?;
  let arms = inbound_arms(wire, inv, all, in_msg.trim_end_matches("Msg"));
  let stem = protocol.trim_end_matches("Protocol");

  let mut traits: Vec<String> = Vec::new();
  for arm in arms.iter().filter(|a| a.inner.is_some()) {
    emit_surface_handler_trait(out, arm)?;
    traits.push(handler_trait(&arm.outer.name));
  }
  emit_envelope_handler_trait(out, &arms)?;
  traits.push(ENVELOPE_TRAIT.to_string());

  emit_bundle_trait(out, &traits, stem);
  emit_route(out, &arms, in_data, in_msg, protocol, stem)
}

fn emit_bundle_trait(out: &mut String, traits: &[String], stem: &str) {
  let bounds = format!("{} + Send + Sync", traits.join(" + "));
  out.push_str(&format!(
    "pub trait {stem}Handlers: {bounds} {{}}\n\nimpl<T> {stem}Handlers for T where T: {bounds} {{}}\n\n"
  ));
}

fn emit_surface_handler_trait(out: &mut String, arm: &InboundArm) -> Result<()> {
  out.push_str(&format!(
    "pub trait {trait_name} {{\n",
    trait_name = handler_trait(&arm.outer.name),
  ));
  for r in arm.requests() {
    out.push_str(&request_method(r));
  }
  for v in arm.dispatched() {
    if v.tag == Some(VariantTag::Response) {
      continue;
    }
    out.push_str(&dispatch_method(&arm.outer.name, v)?);
  }
  out.push_str("}\n\n");
  Ok(())
}

fn emit_envelope_handler_trait(out: &mut String, arms: &[InboundArm]) -> Result<()> {
  out.push_str(&format!("pub trait {ENVELOPE_TRAIT} {{\n"));
  for arm in arms.iter().filter(|a| a.inner.is_none()) {
    out.push_str(&dispatch_method("envelope", arm.outer)?);
  }
  out.push_str("}\n\n");
  Ok(())
}

fn request_method(r: &TypedRequestEntry) -> String {
  let carried = if r.carries_request_id() {
    "&self, id: Uuid"
  } else {
    "&self"
  };
  let args = if r.request_takes_payload {
    format!("{carried}, request: {}", r.request)
  } else {
    carried.to_string()
  };
  format!(
    "  fn {method}({args}) -> impl Future<Output = Result<Reply<{response}>, HandlerError<{error}>>> + Send;\n",
    method = snake(&r.request_variant_pascal()),
    response = r.response,
    error = r
      .error
      .clone()
      .unwrap_or_else(|| "::core::convert::Infallible".to_string()),
  )
}

fn dispatch_method(owner: &str, v: &WireVariant) -> Result<String> {
  if v.is_struct {
    return Err(anyhow!(
      "rust dispatch: `{owner}.{}` is a struct-shaped variant; the inbound arm has no shape for it",
      v.name
    ));
  }
  let args = match v.payload.as_ref() {
    None => "&self".to_string(),
    Some(p) => format!("&self, payload: {}", payload_rust(p)),
  };
  Ok(format!(
    "  fn {method}({args}) -> impl Future<Output = Result<(), WireError>> + Send;\n",
    method = snake(&v.name),
  ))
}

fn emit_route(
  out: &mut String,
  arms: &[InboundArm],
  in_data: &str,
  in_msg: &str,
  protocol: &str,
  stem: &str,
) -> Result<()> {
  out.push_str(&format!(
    "pub async fn route<H>(handlers: &Arc<H>, msg: {in_msg}, conn: &Connection<{protocol}>) -> Result<(), SdkError>\nwhere\n  H: {stem}Handlers + 'static,\n{{\n  let {in_msg} {{ id, data, .. }} = msg;\n  match data {{\n"
  ));
  for arm in arms {
    match arm.inner {
      Some(inner) => emit_surface_arms(out, arm, &inner.name, in_data)?,
      None => out.push_str(&envelope_arm(arm.outer, in_data)?),
    }
  }
  out.push_str("  }\n}\n");
  Ok(())
}

fn emit_surface_arms(out: &mut String, arm: &InboundArm, inner: &str, in_data: &str) -> Result<()> {
  let outer = &arm.outer.name;
  let handler = handler_trait(outer);

  for r in arm.requests() {
    let method = snake(&r.request_variant_pascal());
    let held = if r.is_concurrent() { "&handlers" } else { "handlers" };
    let carried = if r.carries_request_id() { ", id" } else { "" };
    let (bind, call) = if r.request_takes_payload {
      (
        "(request)",
        format!("<H as {handler}>::{method}({held}{carried}, request)"),
      )
    } else {
      ("", format!("<H as {handler}>::{method}({held}{carried})"))
    };
    let pattern = format!(
      "{in_data}::{outer}({inner}::{variant}{bind})",
      variant = r.request_variant_pascal(),
    );
    let body = reply_body(r, &call);
    if r.is_concurrent() {
      out.push_str(&format!(
        "    {pattern} => {{\n      let handlers = handlers.clone();\n      let conn = conn.clone();\n      rt::spawn(async move {{\n        if let Err(error) = {body} {{\n          tracing::warn!(surface = \"{prop}\", variant = \"{disc}\", ?error, \"the reply did not reach the peer\");\n        }}\n      }});\n      Ok(())\n    }}\n",
        prop = arm.prop(),
        disc = r.request_disc,
      ));
    } else {
      out.push_str(&format!("    {pattern} => {body},\n"));
    }
  }

  for v in arm.dispatched() {
    let is_response = v.tag == Some(VariantTag::Response);
    let bind = match (v.payload.as_ref(), is_response) {
      (None, _) => "",
      (Some(_), true) => "(_)",
      (Some(_), false) => "(payload)",
    };
    let pattern = format!("{in_data}::{outer}({inner}::{}{bind})", v.name);
    let disc = rename_camel(&v.name);
    if is_response {
      out.push_str(&format!(
        "    {pattern} => {{\n      tracing::debug!(surface = \"{prop}\", variant = \"{disc}\", \"response with no pending request\");\n      Ok(())\n    }}\n",
        prop = arm.prop(),
      ));
      continue;
    }
    let call = format!("<H as {handler}>::{}(handlers{})", snake(&v.name), payload_argument(v));
    out.push_str(&unhandled_arm(&pattern, &call, &arm.prop(), &disc));
  }
  Ok(())
}

fn reply_body(r: &TypedRequestEntry, call: &str) -> String {
  let lane = if r.is_bulk_byte_stream() {
    "Priority::Bulk"
  } else {
    "Priority::Normal"
  };
  format!(
    "match {call}.await {{\n      Ok(reply) => {{\n        let sent = conn\n          .respond_to_with::<{req}>(id, reply.response, reply.priority.unwrap_or({lane}), reply.compress)\n          .await;\n        if let Some(after) = reply.after {{\n          after.await;\n        }}\n        sent\n      }}\n      Err(HandlerError::Domain(error)) => conn.respond_err::<{req}>(id, error).await,\n      Err(HandlerError::Wire(error)) => conn.respond(id, error.into()).await,\n    }}",
    req = r.request,
  )
}

fn envelope_arm(v: &WireVariant, in_data: &str) -> Result<String> {
  if v.is_struct {
    return Err(anyhow!(
      "rust dispatch: envelope variant `{}` is struct-shaped; the inbound arm has no shape for it",
      v.name
    ));
  }
  let bind = if v.payload.is_some() { "(payload)" } else { "" };
  let pattern = format!("{in_data}::{}{bind}", v.name);
  let call = format!(
    "<H as {ENVELOPE_TRAIT}>::{}(handlers{})",
    snake(&v.name),
    payload_argument(v)
  );
  Ok(unhandled_arm(&pattern, &call, "envelope", &rename_camel(&v.name)))
}

fn payload_argument(v: &WireVariant) -> &'static str {
  match (v.payload.is_some(), v.boxed) {
    (false, _) => "",
    (true, true) => ", *payload",
    (true, false) => ", payload",
  }
}

fn unhandled_arm(pattern: &str, call: &str, surface: &str, disc: &str) -> String {
  format!(
    "    {pattern} => {{\n      if let Err(error) = {call}.await {{\n        tracing::warn!(surface = \"{surface}\", variant = \"{disc}\", ?error, \"inbound not handled\");\n      }}\n      Ok(())\n    }}\n"
  )
}

fn payload_rust(p: &PayloadType) -> String {
  match p {
    PayloadType::Named(n) => n.clone(),
    PayloadType::Bytes => "Vec<u8>".to_string(),
    PayloadType::JsonValue => "serde_json::Value".to_string(),
    PayloadType::StringScalar => "String".to_string(),
  }
}

fn snake(pascal: &str) -> String {
  let chars: Vec<char> = pascal.chars().collect();
  let mut out = String::new();
  for (i, ch) in chars.iter().enumerate() {
    if ch.is_uppercase() {
      let prev_lower = i > 0 && chars[i - 1].is_lowercase();
      let next_lower = i + 1 < chars.len() && chars[i + 1].is_lowercase();
      if i > 0 && (prev_lower || next_lower) {
        out.push('_');
      }
      out.extend(ch.to_lowercase());
    } else {
      out.push(*ch);
    }
  }
  if is_keyword(&out) { format!("r#{out}") } else { out }
}

fn is_keyword(s: &str) -> bool {
  matches!(
    s,
    "as"
      | "break"
      | "const"
      | "continue"
      | "crate"
      | "else"
      | "enum"
      | "extern"
      | "false"
      | "fn"
      | "for"
      | "if"
      | "impl"
      | "in"
      | "let"
      | "loop"
      | "match"
      | "mod"
      | "move"
      | "mut"
      | "pub"
      | "ref"
      | "return"
      | "self"
      | "static"
      | "struct"
      | "super"
      | "trait"
      | "true"
      | "type"
      | "unsafe"
      | "use"
      | "where"
      | "while"
      | "async"
      | "await"
      | "dyn"
  )
}
