	/// Receiver does not recognize this request variant, or recognizes it but cannot map the request to any operation it serves
	case unsupported
	/// Receiver recognizes the variant but the backend is not yet wired
	case unimplemented
	/// Receiver could not decode or validate the request payload
	case malformed(WireErrorMalformedInner)
	/// Unexpected internal error while handling the request
	case handlerFailed(WireErrorHandlerFailedInner)

	enum CodingKeys: String, CodingKey, Codable {
		case unsupported,
			unimplemented,
			malformed,
			handlerFailed
	}

	private enum ContainerCodingKeys: String, CodingKey {
		case type, data
	}

	public init(from decoder: Decoder) throws {
		let container = try decoder.container(keyedBy: ContainerCodingKeys.self)
		if let type = try? container.decode(CodingKeys.self, forKey: .type) {
			switch type {
			case .unsupported:
				self = .unsupported
				return
			case .unimplemented:
				self = .unimplemented
				return
			case .malformed:
				if let content = try? container.decode(WireErrorMalformedInner.self, forKey: .data) {
					self = .malformed(content)
					return
				}
			case .handlerFailed:
				if let content = try? container.decode(WireErrorHandlerFailedInner.self, forKey: .data) {
					self = .handlerFailed(content)
					return
				}
			}
		}
