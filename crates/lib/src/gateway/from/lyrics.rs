use bridgething_macros::BridgeEnum;
use derive_more::derive::Debug;
use serde::{Deserialize, Serialize};
use ts_rs::TS;
use typeshare::typeshare;

#[typeshare]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "gateway.ts")]
pub struct LyricLine {
  pub start_ms: u32,
  pub text: String,
}

#[typeshare]
#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "gateway.ts")]
pub struct Lyrics {
  pub synced: Option<Vec<LyricLine>>,
  pub plain: Option<String>,
  pub source: String,
}

/// Reply to `LyricsRequest`. `lyrics: None` means the resolver chain ran
/// to completion without a hit (e.g. lrclib 404, no fallback configured)
/// and is distinct from `LyricsErrorReply` which signals a transient
/// failure (network, parse, resolver-internal error).
#[typeshare]
#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "gateway.ts")]
pub struct LyricsReply {
  pub lyrics: Option<Lyrics>,
}

#[typeshare]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "gateway.ts")]
pub struct LyricsErrorReply {
  pub message: String,
}

#[typeshare]
#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS, BridgeEnum)]
#[serde(tag = "event", content = "data", rename_all = "camelCase")]
#[ts(export, export_to = "gateway.ts")]
#[bridge_enum(into = crate::gateway::GatewayToBridgeMsgData)]
pub enum GatewayToBridgeLyricsMsg {
  #[bridge_response]
  LyricsReply(LyricsReply),
  #[bridge_response]
  LyricsErrorReply(LyricsErrorReply),
}
